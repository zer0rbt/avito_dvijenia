#!/usr/bin/env bash
# Поднять туннель в фоне и напечатать выданный адрес.
#
# ВНИМАНИЕ: в текущем окружении быстрый туннель trycloudflare до конца НЕ
# заработал — по http2 Cloudflare не маршрутизирует (530/Argo 1033), по
# QUIC маршрутизирует, но UDP через VPN рвётся. Подробности и что делать
# дальше — B-025 в docs/BACKLOG.md. Скрипт оставлен рабочим: он корректен,
# упирается всё в сеть.
#
# Отдельно от run_tunnel.sh: тот держит туннель на переднем плане (`make
# tunnel`), а этот нужен для запуска из другой оболочки — поднял, вернул
# адрес, вышел.
#
# --protocol http2 не для красоты: по умолчанию cloudflared ходит по QUIC
# (UDP/7844), а через VPN этого окружения UDP не проходит — туннель
# поднимается, но отдаёт 502, и в логе идёт «timeout: no recent network
# activity». На http2 всё работает.
set -euo pipefail

PORT="${PORT:-8000}"
BIN="${CLOUDFLARED:-$HOME/.local/bin/cloudflared}"
# Свой файл на каждый запуск. Общий лог путал: убитый процесс дописывал в
# него свои прощальные строки уже после того, как файл обнулили под новый
# запуск, и выглядело это как «новый туннель сразу умер».
LOG="${TUNNEL_LOG:-/tmp/tunnel-$(date +%H%M%S).log}"
ln -sf "$LOG" /tmp/tunnel-last.log

# Убиваем только сам бинарь по имени, а не по подстроке "cloudflared":
# pkill -f поймал бы и вызывающую команду, если она это слово содержит,
# и снёс бы вызывающий шелл (проверено, exit 15).
pkill -x cloudflared 2>/dev/null || true
for _ in $(seq 1 10); do
    pgrep -x cloudflared >/dev/null || break
    sleep 1
done
# origin — 127.0.0.1, а НЕ localhost. localhost резолвится в ::1 первым, а
# uvicorn слушает 0.0.0.0, то есть только IPv4: cloudflared стучался в
# [::1]:8000, получал отказ и отдавал 502 при живом туннеле.
# --edge-ip-version 4 — по той же причине снаружи: IPv6-маршрут в этом
# окружении отваливается (B-013).
# Протокол НЕ переопределяем. Соблазн поставить --protocol http2 велик
# (precheck на QUIC иногда ругается), но с быстрым туннелем trycloudflare
# это ломает маршрутизацию: соединение регистрируется, а Cloudflare на
# каждый запрос отдаёт 530 (Argo 1033, «туннель не подключён»). На QUIC
# край маршрутизирует — проверено: там приходил 502 от самого cloudflared,
# то есть запрос до него доезжал.
nohup "$BIN" tunnel --url "http://127.0.0.1:${PORT}" --no-autoupdate >>"$LOG" 2>&1 &

url=""
for _ in $(seq 1 40); do
    url=$(grep -oE 'https://[a-z0-9-]+\.trycloudflare\.com' "$LOG" | head -1 || true)
    [ -n "$url" ] && break
    sleep 1
done
if [ -z "$url" ]; then
    echo "адрес не появился, смотри $LOG" >&2
    exit 1
fi

# Адрес печатается сразу, а маршрут поднимается позже. Ждём, пока туннель
# реально начнёт отвечать: иначе получаем 530 (Argo 1033 — «туннель не
# подключён») и думаем, что всё сломано.
#
# Проверяем не запросом наружу, а состоянием соединений в логе: из этого
# WSL публичный адрес не открывается вовсе (curl отдаёт 000, при том что
# GitHub из того же WSL качается) — сеть окружения, B-013. Значит curl
# отсюда о работоспособности туннеля ничего не говорит.
for _ in $(seq 1 40); do
    registered=$(grep -c 'Registered tunnel connection' "$LOG" || true)
    failed=$(grep -c 'Failed to dial' "$LOG" || true)
    if [ "$registered" -ge 4 ] && [ "$failed" -eq 0 ]; then
        echo "$url"
        exit 0
    fi
    sleep 3
done

echo "$url"
echo "соединений: ${registered:-0}, ошибок подключения: ${failed:-0}; лог: $LOG" >&2
exit 2
