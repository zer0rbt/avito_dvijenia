"""Определение категорийных полей по названию товара (B-010).

Почему по названию, а не по фото. Заказчик предложил «по фото + по
описанию, желательно что-то готовое». По фото сейчас нечего классифицировать:
из 82 позиций каталога фото есть у одной (B-018 — веб-превью TG отдаёт
только последние ~20 постов). Классификатор по фото на таком входе просто
не запустится. Плюс готовые модели (CLIP и подобные) — это сотни мегабайт
весов и GPU-зависимость ради задачи, где название товара уже содержит ответ
прямым текстом: «ХУДИ ALEXANDER MCQUEEN», «Утки Поло», «Свитер ERD».

Поэтому здесь словарь ключевых слов по справочнику GoodsSubType из
avito/data/categories.yaml. Он разбирает реальный каталог почти целиком,
работает мгновенно и объясним: видно, какое слово дало какой ответ.
Не опознали — не гадаем, возвращаем None, карточка уходит оператору
(та же доктрина, что у require_verified()).

Когда появится телетон-выгрузка фото (B-018) и накопится размеченная
очередь модерации, сюда можно добавить второй проход по фото для остатка.
"""

from __future__ import annotations

import re

# Ключевое слово -> значение GoodsSubType из справочника Авито.
# Порядок важен: более длинные/специфичные основы проверяются первыми,
# иначе «зип худи» уедет в «Кофта» по подстроке.
GOODS_SUBTYPE_KEYWORDS: list[tuple[str, str]] = [
    ("зип худи", "Худи"),
    ("зип-худи", "Худи"),
    ("худи", "Худи"),
    ("hoodie", "Худи"),
    ("толстовк", "Толстовка"),
    ("свитшот", "Свитшот"),
    ("sweatshirt", "Свитшот"),
    ("футболк", "Футболка"),
    ("t-shirt", "Футболка"),
    ("tshirt", "Футболка"),
    ("поло", "Поло"),
    ("polo", "Поло"),
    ("майк", "Майка"),
    ("джемпер", "Джемпер"),
    ("кардиган", "Кардиган"),
    ("свитер", "Свитер"),
    ("sweater", "Свитер"),
    ("лонгслив", "Футболка"),
    ("кофт", "Кофта"),
]


def classify_goods_subtype(title: str, description: str = "") -> tuple[str | None, str | None]:
    """(GoodsSubType, по какому слову решили). None — не опознали.

    Сначала название: там тип товара стоит прямым текстом. Описание —
    запасной вход, для источников, которые кладут тип не в заголовок.
    """
    for haystack in (title, description):
        if not haystack:
            continue
        lowered = haystack.lower().replace("ё", "е")
        for keyword, subtype in GOODS_SUBTYPE_KEYWORDS:
            if re.search(rf"\b{re.escape(keyword)}", lowered):
                return subtype, keyword
    return None, None


def classify_product(title: str, description: str = "") -> dict[str, str | None]:
    """Всё, что умеем определить по тексту. Сейчас это только GoodsSubType:
    GoodsType/Apparel/Category у нас постоянные (defaults в categories.yaml),
    потому что сверена одна категория — «Кофты и футболки»."""
    subtype, matched = classify_goods_subtype(title, description)
    return {"GoodsSubType": subtype, "matched_keyword": matched}
